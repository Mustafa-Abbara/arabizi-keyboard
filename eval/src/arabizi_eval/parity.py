def _converter_and_hashes() -> tuple[b0.RuleConverter, dict]:
    rules_bytes, lexicon_bytes = b0.RULES_PATH.read_bytes(), b0.LEXICON_PATH.read_bytes()
    converter = b0.RuleConverter(rules=json.loads(rules_bytes), lexicon=json.loads(lexicon_bytes))
    hashes = {"rules_sha256": hashlib.sha256(rules_bytes).hexdigest(),
              "lexicon_sha256": hashlib.sha256(lexicon_bytes).hexdigest()}
    return converter, hashes


def short_hash(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:HASH_CHARS]


def build() -> dict:
    converter, hashes = _converter_and_hashes()
    corpus: dict[str, str] = {}
    for name in CORPUS:
        for _, row, err in P.read_jsonl(P.ROOT / name):
            if err:
                raise SystemExit(f"{name}: {err}")
            corpus[row["id"]] = short_hash(converter.convert(row["arabizi"]))
    words = sorted(converter.words)
    return {
        "_comment": "Generated by `python -m arabizi_eval.parity` (eval/src/arabizi_eval/parity.py); do not edit. "
                    "The Swift RuleConverter must reproduce Python's B0 exactly.",
        **hashes,
        "cases": [[text, converter.convert(text)] for text in CASES],
        "corpus": {"files": CORPUS, "hash_chars": HASH_CHARS, "outputs": dict(sorted(corpus.items()))},
        "letters": {"words": len(words),
                    "outputs_sha256": hashlib.sha256(
                        "\n".join(b0.letters(w, converter.rules) for w in words).encode("utf-8")).hexdigest()},
    }


def render(fixture: dict) -> str:
    return json.dumps(fixture, ensure_ascii=False, indent=1) + "\n"


def write() -> None:
    FIXTURE.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE.write_text(render(build()), encoding="utf-8")


def is_current() -> bool:
    return FIXTURE.exists() and FIXTURE.read_text(encoding="utf-8") == render(build())


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only check that the fixture is up to date")
    args = parser.parse_args(argv)
    if args.check:
        if is_current():
            print(f"{FIXTURE.name} is up to date")
            return 0
        print(f"{FIXTURE.name} is out of date: run `uv run --project eval python -m arabizi_eval.parity`",
              file=sys.stderr)
        return 1
    write()
    print(f"wrote {FIXTURE.relative_to(P.ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
