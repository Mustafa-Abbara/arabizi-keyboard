    "bel LAU", "bel beit", "la el beit", "lal beit", "mnel beit", "3al beit", "3al 7:30?", "b3at 100$ la",
    "b3at $100 w 50%", "2pm aw 3am", "10k aw 1.5k", "1,000,000", "7elo", "3'ayr", "7'abibi", "ma3'", "3ndi",
    "kifak, shu 3am ta3mel?", "KIFAK", "Kifak", "shu;", "shu,3am", "(ktir)", "\"hala\"", "ktir!!!", "...ktir",
    "shuf www.lau.edu, @rami #lebanon 😂", "https://lau.edu.lb/x?y=1", "http://", "rami@lau.edu.lb", "a@b",
    "@rami, #lebanon!", "@", "#", "😂😂", "👍🏽 tamem", "🇱🇧", "❤️ ktir", "1️⃣", "ana w Rami", "ana w @rami",
    "w 100", "el 3am", "w el 2pm", "w, el beit", "w (el) beit", "w el (beit)", "w el beit?",
    "shu\tkifak", "shu\nkifak", "kifak\n", "a_b", "_comment", "café", "café", "naïve", "شو 3am", "٣am",
